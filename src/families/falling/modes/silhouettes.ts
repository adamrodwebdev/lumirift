/** Number of cells to fill. */
export const silhouetteArea = (silhouette: Silhouette): number =>
  silhouette.rows.reduce((sum, row) => sum + (row.match(/#/g) ?? []).length, 0);

/** The silhouette of a given local day: the same for everybody, a new one each day. */
export function silhouetteOfDay(date: Date): Silhouette {
  const day = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000,
  );
  return SILHOUETTES[day % SILHOUETTES.length]!;
}
